import csv
from pathlib import Path

import numpy as np
import synthterrain
from synthterrain.crater import profile

OUTPUT = Path("validation/references/craters/synthterrain_profiles.csv")
FRACTIONS = np.round(np.linspace(0.0, 1.6, 33), 9)
INTERIOR = FRACTIONS[FRACTIONS <= 1.0]


def main():
    rows = []
    ft = profile.FT_Crater(100.0)
    for name, radius_fix in (("ft_original", False), ("ft_at_one_radius", True)):
        heights = ft.profile(FRACTIONS.copy(), radius_fix=radius_fix)
        rows += [(name, 100.0, 0.0, 0.0, r, h) for r, h in zip(FRACTIONS, heights)]
    for diameter, depth in ((100.0, 13.0), (30.0, 3.3)):
        heights = profile.FTmod_Crater(diameter, depth=depth).profile(FRACTIONS.copy())
        rows += [("ft_plateau", diameter, depth, 0.0, r, h) for r, h in zip(FRACTIONS, heights)]
    for diameter, depth, rim_scale in ((100.0, 20.0, 1.0), (100.0, 12.0, 0.6), (40.0, 3.0, 0.3)):
        rim = rim_scale * profile.MPD_Crater.height_r_naught(diameter)
        crater = profile.MPD_Crater(diameter, depth, rim_height=rim)
        rows += [("mpd", diameter, depth, rim, r, crater.profile(r)) for r in INTERIOR]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", newline="") as handle:
        handle.write(f"# synthterrain {synthterrain.__version__}; generated by {Path(__file__).name}\n")
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["name", "diameter_m", "depth_m", "rim_height_m", "radius_fraction", "height_m"])
        for name, diameter, depth, rim, r, h in rows:
            writer.writerow([name, repr(float(diameter)), repr(float(depth)), repr(float(rim)),
                             repr(float(r)), repr(float(h))])


if __name__ == "__main__":
    main()
