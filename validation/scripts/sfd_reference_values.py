import csv
from pathlib import Path

import numpy as np
import synthterrain
from synthterrain.crater import age, functions

OUTPUT = Path("validation/references/sfd/synthterrain_reference.csv")
DIAMETERS = np.round(np.logspace(-1, 4, 26), 9)


def main():
    distributions = {
        "trask": functions.Trask(a=0.01),
        "viper": functions.VIPER_Env_Spec(a=0.01),
        "npf": functions.NPF(a=10, b=300000),
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", newline="") as handle:
        handle.write(f"# synthterrain {synthterrain.__version__}; generated by {Path(__file__).name}\n")
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["name", "diameter_m", "value"])
        for name, distribution in distributions.items():
            for diameter in DIAMETERS[DIAMETERS >= distribution.a]:
                value = float(np.asarray(distribution.csfd(np.array([diameter])))[0])
                writer.writerow([name, repr(float(diameter)), repr(value)])
        npf = distributions["npf"]
        trask = distributions["trask"]
        for diameter in DIAMETERS[DIAMETERS >= npf.a]:
            years = age.equilibrium_age(np.array([diameter]), npf.csfd, trask.csfd)[0]
            writer.writerow(["equilibrium_age_gyr", repr(float(diameter)), repr(float(years) / 1e9)])


if __name__ == "__main__":
    main()
